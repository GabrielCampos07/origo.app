-- Least-privilege DB access: api_app_role for authentication tables
-- =============================================================================
-- 
-- PURPOSE:
--   Grant SELECT + UPDATE on users, SELECT + INSERT + UPDATE on token tables
--   to api_app_role for login/auth flows (prod login currently 500 because
--   only legal+referral grants exist in 01/02).
--
-- WHEN TO RUN:
--   - After P0 auth migrations have been applied to the target database.
--   - After 01_api_app_role_legal_acceptances.sql has been applied.
--   - After 02_api_app_role_referral_tables.sql has been applied.
--   - Before the API application switches to using api_app_role credentials.
--
-- IDEMPOTENT:
--   Safe to re-run multiple times. Uses IF NOT EXISTS, explicit REVOKE ALL,
--   and DO $$ blocks for idempotent role/grant operations.
--
-- SECURITY POLICY:
--   users:
--     - SELECT: API can read user profiles for authentication/authorization
--     - UPDATE: API can update lastLoginAt, password hash, profile fields
--     - NO INSERT: signup/cadastro on HOLD (elevated role required)
--     - NO DELETE: user removal reserved for DBA/compliance role only
--     - ⚠️  UPDATE is table-wide — app/Back Sec MUST NOT escalate `role` field
--         without additional row-level security policy (RLS) enforcement
--   
--   password_reset_tokens:
--     - SELECT: API can validate reset tokens
--     - INSERT: API can create new password reset requests
--     - UPDATE: API can mark tokens as used/invalidated
--     - NO DELETE: D8 purge requires elevated role (future origo_cron role)
--   
--   refresh_tokens:
--     - SELECT: API can validate refresh tokens
--     - INSERT: API can create new refresh tokens at login
--     - UPDATE: API can rotate/revoke tokens
--     - NO DELETE: D8 purge requires elevated role (future origo_cron role)
--
-- FUTURE WORK:
