-- Create api_app_role if it doesn't exist
-- Note: Password must be set separately via ALTER ROLE or environment config
-- Note: This role may already exist from 01/02 scripts
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT FROM pg_catalog.pg_roles WHERE rolname = 'api_app_role'
  ) THEN
    CREATE ROLE api_app_role WITH LOGIN;
    RAISE NOTICE 'Created role: api_app_role';
  ELSE
    RAISE NOTICE 'Role api_app_role already exists';
  END IF;
END
$$;

-- Grant USAGE on schema public (required for accessing objects)
-- Idempotent: safe to grant multiple times
GRANT USAGE ON SCHEMA public TO api_app_role;

-- ==================== users ====================
-- Explicit least privilege: REVOKE ALL first, then grant only what's needed
REVOKE ALL ON TABLE public.users FROM api_app_role;

-- Grant SELECT + UPDATE only on users
-- NO INSERT (signup on hold), NO DELETE (user removal = DBA/compliance only)
GRANT SELECT, UPDATE ON TABLE public.users TO api_app_role;

-- ⚠️  SECURITY NOTE:
-- UPDATE privilege is table-wide. Application MUST enforce business rules to
-- prevent unauthorized role escalation (e.g., student → admin). Consider RLS
-- policies or app-level authorization checks before allowing role field updates.

-- ==================== password_reset_tokens ====================
-- Explicit least privilege: REVOKE ALL first, then grant only what's needed
REVOKE ALL ON TABLE public.password_reset_tokens FROM api_app_role;

-- Grant SELECT + INSERT + UPDATE on password_reset_tokens
-- NO DELETE (D8 purge = elevated role, see FUTURE WORK above)
GRANT SELECT, INSERT, UPDATE ON TABLE public.password_reset_tokens TO api_app_role;

-- ==================== refresh_tokens ====================
-- Explicit least privilege: REVOKE ALL first, then grant only what's needed
REVOKE ALL ON TABLE public.refresh_tokens FROM api_app_role;

-- Grant SELECT + INSERT + UPDATE on refresh_tokens
-- NO DELETE (D8 purge = elevated role, see FUTURE WORK above)
GRANT SELECT, INSERT, UPDATE ON TABLE public.refresh_tokens TO api_app_role;

-- Note: Token table IDs use CUID (generated by app), no sequence grant needed

